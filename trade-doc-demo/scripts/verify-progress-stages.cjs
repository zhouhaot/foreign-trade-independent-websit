/* 核对订单汇总阶段，避免把未开始或部分单证误画为全部完成。 */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const context = vm.createContext({ document: { addEventListener() {} }, App: { user: null }, AppUI: {}, location: { hash: '#/orders' }, setTimeout() {} });
context.window = context;
for (const name of ['mock-data', 'utils', 'views-core', 'views-sales']) {
  vm.runInContext(fs.readFileSync(path.join(root, 'js', name + '.js'), 'utf8'), context, { filename: name });
}
const { Views, U, MOCK } = context;
context.App.user = U.roleUser('boss');
function track(id) {
  context.AppUI.orders = { page: 1, filters: { no: id } };
  const html = Views.orders();
  const match = html.match(/<section class="inspector-track track-doc">([\s\S]*?)<\/section>/);
  assert.ok(match, '存在单证独立进度');
  return match[1];
}
const count = (html, name) => (html.match(new RegExp('class="step ' + name + '"', 'g')) || []).length;
let html = track('SO2026003');
assert.match(html, />制作<span/);
assert.match(html, />送审<span/);
assert.match(html, />审核<span/);
assert.match(html, />可导出<span/);
assert.match(html, /role="list" aria-label="单证阶段"/);
assert.match(html, /条件尚未满足/);
assert.equal(count(html, 'done'), 0, '没有单证不能画已完成');
assert.match(html, /尚未制作单证/);
html = track('SO2026005');
assert.equal(count(html, 'done'), 0, '制作中+退回不能冒称全部制作/送审完成');
assert.match(html, /含退回 1 份/);
assert.equal(count(html, 'ready'), 0);
html = track('SO2026001');
assert.equal(count(html, 'done'), 2, '两类都待审核意味着制作/送审已完成');
assert.equal(count(html, 'warn'), 1);
assert.equal(count(html, 'ready'), 0, '待审核不可导出');
html = track('SO2026002');
assert.equal(count(html, 'done'), 3, '全部通过只完成制作/送审/审核');
assert.equal(count(html, 'ready'), 1, '可导出只是资格');
assert.ok(!html.includes('已导出'));
const cancelled = U.order('SO2026002');
cancelled.status = '已取消';
html = track(cancelled.id);
assert.equal(count(html, 'ready'), 0, '取消订单不展示继续导出资格');
assert.match(html, /订单已取消，导出资格需重新核对/);
cancelled.status = '执行中';
const returnedDocs = MOCK.documents.filter(d => d.orderId === 'SO2026001');
const oldStates = returnedDocs.map(d => d.status);
returnedDocs.forEach(d => { d.status = '已退回'; });
html = track('SO2026001');
assert.equal(count(html, 'done'), 0, '两类都退回仍需重新制作送审');
assert.match(html, /曾送审 2\/2 类/);
assert.match(html, /修订后重新送审/);
assert.match(html, /role="listitem" aria-current="step"/);
returnedDocs.forEach((d, i) => { d.status = oldStates[i]; });
const order = U.order('SO2026001');
const ci = MOCK.documents.find(d => d.orderId === order.id && d.type === 'CI');
const newer = { ...ci, id: ci.id + '-NEW', version: ci.version + 1, status: '制作中' };
MOCK.documents.push(newer);
html = track(order.id);
assert.equal(count(html, 'done'), 0, '旧版已送审不得覆盖新版制作中');
assert.match(html, /已送审 1\/2 类/);
const detail = Views.orderDetail({ params: [order.id], query: {}, user: context.App.user });
assert.match(detail, /document-stages/);
assert.match(detail, /已送审 1\/2 类/);
assert.equal(U.orderFin(order).received, 12000, '阶段显示不修改收款');
console.log('PASS: no-document, mixed returned/drafting, all reviewing, export eligibility, latest-version aggregate and shared detail stages; payment facts unchanged (Node VM)');
